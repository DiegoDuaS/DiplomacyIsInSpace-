-- The game's own bitmap font, drawn here glyph by glyph. Each glyph is rows of '.' (empty) and
-- '#' (ink), top to bottom: capitals stand on row 7 (the baseline), lowercase on rows 3-7, and
-- g j p q y hang down to row 9. A glyph may be 1 to 5 columns wide; src/graphics/Fonts.lua turns
-- this table into a LÖVE font at any whole-number scale.

local font = { height = 9, glyphs = {} }

local function glyph(ch, rows)
    local width = #rows[1]
    for i, row in ipairs(rows) do
        assert(#row == width, ("font glyph %q: row %d is not %d wide"):format(ch, i, width))
    end
    font.glyphs[#font.glyphs + 1] = { ch = ch, rows = rows, width = width }
end

local function blank(width)
    return string.rep(".", width)
end

-- rows given from the top (row 1); missing rows below are filled with blanks
local function define(ch, text)
    local rows = {}
    for line in text:gmatch("[^\n]+") do rows[#rows + 1] = line end
    local width = #rows[1]
    while #rows < font.height do rows[#rows + 1] = blank(width) end
    glyph(ch, rows)
end


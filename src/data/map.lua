local TERRAIN = {
    ["#"] = "asteroid",
    ["."] = false,
}

-- col, row, w, h: the block's top-left cell and its size in cells; range is in cells.
MapData.pois = {
    { id = "station", kind = "station", name = "CONCORD STATION", col = 39, row = 23, w = 4, h = 4, range = 5.6 },
    { id = "thalassa", kind = "planet", alien = "kelari", col = 12, row = 10, w = 6, h = 6, range = 6 },
    { id = "krag", kind = "planet", alien = "vorn", col = 64, row = 12, w = 6, h = 6, range = 6 },
    { id = "hexa", kind = "planet", alien = "ixili", col = 22, row = 34, w = 6, h = 6, range = 6 },
}

MapData.start = { col = 40, row = 28.5 }

function MapData.build()
    local width = #ROWS[1]
    local grid = TileGrid.new(width, #ROWS)

    for y, row in ipairs(ROWS) do
        assert(#row == width, ("map row %d has the wrong width"):format(y))
        for x = 1, width do
            local glyph = row:sub(x, x)
            local terrain = TERRAIN[glyph]
            assert(terrain ~= nil, ("unknown map glyph %q at %d,%d"):format(glyph, x, y))
            if terrain then
                grid:set(x, y, terrain)
            end
        end
    end

    for _, poi in ipairs(MapData.pois) do
        for y = poi.row, poi.row + poi.h - 1 do
            for x = poi.col, poi.col + poi.w - 1 do
                grid:set(x, y, poi.id)
            end
        end
    end

    return grid
end

return MapData
